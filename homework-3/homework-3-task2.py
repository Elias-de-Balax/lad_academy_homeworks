"""Сумма введённых чисел до нуля. Программа вводит числа (int(input(...))) до тех пор, пока пользователь не введёт 0,
   а затем выводит сумму всех введённых чисел. Использовать while и break. Подсказка: накапливайте сумму в переменной,
   а 0 — сигнал остановки."""

sum = 0

while True:
    try:
        n = int(input("Введите число: "))
    except ValueError:
        break

    if n:
        sum += n
    else:
        break

print(f"\nСумма всех чисел: {sum}")