"""Таблица умножения. Считать число n (например, через input), вывести через for и range таблицу умножения для n
   от 1 до 10: `` 5 1 = 5 5 2 = 10 ... ``"""

try:
    n = int(input("Введите число: "))

    for i in range(1, 11):
        print(f"{n} * {i} = {n * i}")
except ValueError:
    print("Неверно введенное значение.")