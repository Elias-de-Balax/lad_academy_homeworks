# CBV в Django строятся на наследовании, потому что это позволяет переиспользовать
# готовую логику из базовых классов (например, обработку HTTP-методов, выбор шаблонов, пагинацию).
# Вызов super() нужен, чтобы корректно запустить эту базовую логику и не потерять важные шаги выполнения.

class MyView(ListView):
    def get_queryset(self):
        # он возвращает базовый QuerySet, если не вызвать, будет потеряна стандартная логика работы ListView
        qs = super().get_queryset()
        return qs.filter(is_active=True)
